import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { Resvg } from '@resvg/resvg-js';
import gifenc from 'gifenc';
import { avatarSVG } from '../src/avatar-svg.mjs';
import { PROVIDERS, STATES } from '../src/constants.mjs';

const { GIFEncoder, quantize, applyPalette } = gifenc;
const root = fileURLToPath(new URL('../assets/demo/', import.meta.url));
const width = 360, height = 520, frames = 48, delay = 50;
const manifest = { version: 1, name: 'Original vector demo — replace with Live2D renders', sourceKind: 'procedural-svg-demo', providers: {} };
await mkdir(root, { recursive: true });
for (const provider of PROVIDERS) {
  manifest.providers[provider] = {};
  await mkdir(path.join(root, provider), { recursive: true });
  for (const state of STATES) {
    const gif = GIFEncoder();
    for (let index = 0; index < frames; index++) {
      const rendered = new Resvg(avatarSVG(provider, state, index * delay / 1000, width, height)).render();
      const rgba = rendered.pixels;
      const palette = [[255, 0, 255], ...quantize(rgba, 127)];
      const indexed = applyPalette(rgba, palette);
      for (let pixel = 0; pixel < indexed.length; pixel++) if (rgba[pixel*4+3] < 128) indexed[pixel] = 0;
      gif.writeFrame(indexed, width, height, { palette, delay, repeat: 0, transparent: true, transparentIndex: 0, dispose: 2 });
    }
    gif.finish();
    const relative = `${provider}/${state}.gif`;
    await writeFile(path.join(root, relative), gif.bytes());
    manifest.providers[provider][state] = relative;
    process.stdout.write(`${provider}/${state}.gif\n`);
  }
}
await writeFile(path.join(root, 'pack.json'), JSON.stringify(manifest, null, 2) + '\n');
await writeFile(path.join(root, 'NOTICE.md'), 'These two placeholder characters are original SVG drawings generated by this project. They are not ZipZipPipe artwork, licensed Live2D models, or the final requested character designs. No third-party character art or Cubism runtime is bundled.\n');
